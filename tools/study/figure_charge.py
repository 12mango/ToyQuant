#!/usr/bin/env python3
"""Regenerate the quickstart's cost figure as an inline SVG, and check the file on disk against it.

Why a script and an SVG rather than a Mermaid chart: `xychart-beta` cannot do a grouped bar chart, a legend, a tick
step, a missing top border or a value label, and it draws dark text on a transparent background -- which is invisible in
Material's dark mode. This file writes the four things a chart needs to be readable in both palettes:

- **no background**: nothing is painted, so the page's own colour shows through;
- **`currentColor`** for the axes, the ticks and every label, so the text is the page's text colour in either mode;
- **two mid-tone series colours** (a blue and a rust) that keep their contrast on white and on `#1e1e1e`;
- **one bar pair per instrument**, because the three markets are discrete: a line between two of them would be a claim
  that the space between them means something.

The numbers are the quickstart table's, and `--check` refuses when the file on disk and this script disagree.

    python3 tools/study/figure_charge.py --emit     # write docs/_figures/charge.svg
    python3 tools/study/figure_charge.py --check    # 0 when the file is this script's output
"""
import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "docs/_figures/charge.svg"
CAPTURE = "#4a7fb5"
COST = "#c2553c"
# The table on the quickstart carries the exact numbers; these are the same values, labelled to three decimals below a
# tenth so the small ones do not round to zero.
MARKETS = [("crypto perpetual", 0.088, 2.57),
           ("micro E-mini", 0.0131, 0.5),
           ("SPY", 0.268, 0.35)]
WIDTH, HEIGHT = 720, 360
LEFT, RIGHT, TOP, BOTTOM = 78, 700, 64, 300
Y_MAX = 3.0
BAR, GAP = 56, 8
TICK = 0.5


def label(value):
    return f"{value:.3f}" if value < 0.1 else f"{value:.2f}"


def y_of(value):
    return BOTTOM - (value / Y_MAX) * (BOTTOM - TOP)


def render():
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {HEIGHT}" role="img" '
           f'style="max-width:100%;height:auto" '
           f'aria-label="One fill captured against one fill cost, in ticks, on three markets">',
           "<!-- Generated by tools/study/figure_charge.py. Transparent background and currentColor text, so the figure "
           "follows the page palette in light and dark mode. -->"]
    # Grid and ticks at a fixed step, no top or right spine: the bars are the subject, not the frame.
    steps = int(round(Y_MAX / TICK))
    for step in range(steps + 1):
        value = step * TICK
        y = y_of(value)
        if step:
            out.append(f'<line x1="{LEFT}" y1="{y:.1f}" x2="{RIGHT}" y2="{y:.1f}" '
                       f'stroke="currentColor" stroke-opacity="0.10"/>')
        out.append(f'<text x="{LEFT - 10}" y="{y + 4:.1f}" text-anchor="end" font-size="11" '
                   f'fill="currentColor" fill-opacity="0.70">{value:.1f}</text>')
    out.append(f'<line x1="{LEFT}" y1="{TOP - 24}" x2="{LEFT}" y2="{BOTTOM}" stroke="currentColor" '
               f'stroke-opacity="0.45"/>')
    out.append(f'<line x1="{LEFT}" y1="{BOTTOM}" x2="{RIGHT}" y2="{BOTTOM}" stroke="currentColor" '
               f'stroke-opacity="0.45"/>')
    # The legend, two swatches and two labels: which series is which is the one thing a reader cannot infer.
    for index, (colour, text) in enumerate(((CAPTURE, "captured spread (ticks)"), (COST, "fill cost (ticks)"))):
        x = LEFT + index * 210
        out.append(f'<rect x="{x}" y="{TOP - 34}" width="12" height="12" rx="2" fill="{colour}"/>')
        out.append(f'<text x="{x + 18}" y="{TOP - 24}" font-size="12" fill="currentColor" '
                   f'fill-opacity="0.85">{text}</text>')
    span = RIGHT - LEFT
    for index, (name, captured, cost) in enumerate(MARKETS):
        centre = LEFT + span * (index + 0.5) / len(MARKETS)
        for offset, value, colour in ((-(BAR + GAP) // 2, captured, CAPTURE), ((BAR + GAP) // 2, cost, COST)):
            x = centre + offset - BAR // 2
            top = y_of(value)
            out.append(f'<rect x="{x:.1f}" y="{top:.1f}" width="{BAR}" height="{BOTTOM - top:.1f}" '
                       f'rx="2" fill="{colour}"/>')
            out.append(f'<text x="{x + BAR / 2:.1f}" y="{top - 7:.1f}" text-anchor="middle" font-size="11" '
                       f'fill="currentColor" fill-opacity="0.85">{label(value)}</text>')
        out.append(f'<text x="{centre:.1f}" y="{BOTTOM + 24}" text-anchor="middle" font-size="12" '
                   f'fill="currentColor" fill-opacity="0.85">{name}</text>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--emit", action="store_true", help="write the SVG")
    parser.add_argument("--check", action="store_true", help="compare the SVG on disk with this script")
    args = parser.parse_args()
    if args.emit == args.check:
        parser.error("choose one of --emit or --check")
    text = render()
    if args.emit:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT} ({len(text)} bytes, {text.count(chr(10))} lines)")
        return 0
    if not OUT.is_file():
        print(f"FAIL {OUT} does not exist")
        return 1
    on_disk = OUT.read_text(encoding="utf-8")
    if on_disk == text:
        print(f"{OUT.name} is this script's output")
        return 0
    print(f"FAIL {OUT.name} differs from this script's output")
    for number, (a, b) in enumerate(zip(on_disk.splitlines(), text.splitlines()), start=1):
        if a != b:
            print(f"  line {number}: on disk {a[:90]!r}")
            print(f"  line {number}: emitted {b[:90]!r}")
            break
    return 1


if __name__ == "__main__":
    sys.exit(main())
